#!/usr/bin/env python3
"""Fail-closed, intentionally small smoke checker for a NEW dbt project.

A deliberately broken fixture counts as detected only on dbt status 'fail'.
A compilation/SQL ERROR, missing selection, skipped test, or silent PASS
makes the runner fail. This is a teaching harness, not a security boundary.
"""
import argparse
import json
import sys
from pathlib import Path

EXPECTED = {
    "positive": (16, "pass", "test"),
    "negative": (7, "fail", "test"),
    "unit": (2, "pass", "unit_test"),
}


# Review-gated roster: unchanged counts are not sufficient proof of coverage.
# Names are generated by pinned dbt 1.12/dbt-utils 1.4.1.
EXPECTED_NAMES = {
    "positive": {
        "accepted_values_dim_products_status__active__inactive",
        "assert_products_not_empty",
        "dbt_utils_expression_is_true_fct_monthly_revenue_gross_amount_discount_amount_net_amount",
        "dbt_utils_expression_is_true_fct_order_revenue_gross_amount_discount_amount_net_amount",
        "dbt_utils_unique_combination_of_columns_fct_monthly_revenue_month_start__product_id",
        "not_null_dim_products_product_id",
        "not_null_dim_products_status",
        "not_null_fct_monthly_revenue_month_start",
        "not_null_fct_monthly_revenue_product_id",
        "not_null_fct_order_revenue_order_id",
        "not_null_stg_orders_order_id",
        "relationships_fct_order_revenue_product_id__product_id__ref_dim_products_",
        "relationships_stg_orders_product_id__product_id__ref_dim_products_",
        "unique_dim_products_product_id",
        "unique_fct_order_revenue_order_id",
        "unique_stg_orders_order_id",
    },
    "negative": {
        "accepted_values_bad_invalid_status_status__active__inactive",
        "assert_bad_empty_model",
        "dbt_utils_expression_is_true_bad_wrong_amount_gross_amount_discount_amount_net_amount",
        "dbt_utils_unique_combination_of_columns_bad_duplicate_composite_month_start__product_id",
        "not_null_bad_null_key_order_id",
        "relationships_bad_orphan_order_product_id__product_id__ref_dim_products_",
        "unique_bad_duplicate_order_order_id",
    },
    "unit": {"revenue_join_and_null_discount", "revenue_zero_discount"},
}

class SmokeFailure(Exception):
    pass


def check(phase, selection_path, result_path):
    count, status, kind = EXPECTED[phase]
    try:
        lines = Path(selection_path).read_text(encoding="utf-8").splitlines()
        selected = [json.loads(line) for line in lines if line.lstrip().startswith("{")]
        selected = [n for n in selected if n.get("resource_type") == kind]
        run = json.loads(Path(result_path).read_text(encoding="utf-8"))
        results = run["results"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise SmokeFailure(f"missing or malformed dbt artifacts: {type(exc).__name__}") from exc
    ids = [n.get("unique_id") for n in selected]
    result_ids = [r.get("unique_id") for r in results]
    if len(ids) != count or None in ids or len(set(ids)) != count:
        raise SmokeFailure(f"wrong {phase} selection: {len(ids)} unique IDs; expected {count}")
    if len(result_ids) != count or None in result_ids or len(set(result_ids)) != count:
        raise SmokeFailure(f"wrong {phase} result inventory")
    actual_names = [n.get("name") for n in selected]
    if (len(EXPECTED_NAMES[phase]) != count or None in actual_names
            or set(actual_names) != EXPECTED_NAMES[phase]
            or len(set(actual_names)) != count):
        raise SmokeFailure(f"unreviewed {phase} test identity or same-count substitution")
    if set(ids) != set(result_ids):
        raise SmokeFailure(f"selected tests differ from executed {phase} tests")
    unexpected = [(r["unique_id"], r.get("status")) for r in results if r.get("status") != status]
    if unexpected:
        raise SmokeFailure(f"expected every {phase} test to be {status}: {unexpected}")
    return count


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("phase", choices=EXPECTED, help="Expected test phase")
    parser.add_argument("selection")
    parser.add_argument("results")
    args = parser.parse_args()
    try:
        count = check(args.phase, args.selection, args.results)
    except SmokeFailure as exc:
        print(f"FAIL-CLOSED {args.phase}: {exc}", file=sys.stderr)
        return 1
    print(f"PASS {args.phase}: {count} selected tests returned expected status")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
